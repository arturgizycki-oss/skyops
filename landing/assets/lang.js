function landLang() {
  const q = new URLSearchParams(location.search).get("lang");
  if (q && LAND[q.toLowerCase()]) return q.toLowerCase();
  try {
    const v = localStorage.getItem("skyops.lang");
    if (v && LAND[v]) return v;
  } catch { /* private mode */ }
  return "pl";
}

let L = landLang();

function applyLand() {
  document.documentElement.lang = L;
  const dict = LAND[L] || LAND.pl;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const v = dict[el.getAttribute("data-i18n")];
    if (v !== undefined) el.innerHTML = v;
  });
  document.querySelectorAll("#lang-land button").forEach(b =>
    b.classList.toggle("on", b.dataset.lang === L));
  // links into the dashboard should carry the language too
  document.querySelectorAll('a[href^="/app"]').forEach(a => {
    a.href = "/app" + (L === "en" ? "?lang=en" : "");
  });
}

function setLand(code) {
  if (!LAND[code]) return;
  L = code;
  try { localStorage.setItem("skyops.lang", code); } catch { /* ignore */ }
  applyLand();
}

document.addEventListener("DOMContentLoaded", () => {
  const sw = document.getElementById("lang-land");
  if (sw) sw.addEventListener("click", e => {
    const b = e.target.closest("button[data-lang]");
    if (b) setLand(b.dataset.lang);
  });
  applyLand();
});
